// The ESP32-S3's PIE (Processor Instruction Extensions): 128-bit q0-q7
// registers, every mnemonic starting with ee. Generated from GNU as
// (xtensa-esp32s3-elf-as, esp-14.2.0): each operand bit's position was
// found by assembling encodings that differ in that bit alone, and the
// immediates' ranges and steps by trying every value; 2248 random
// operand combinations then encoded exactly as as does. Fields are often
// split (q registers in bits 15, 20, 21; an immediate's sign in bit 22),
// hence a list of bit positions per operand. All are 3 bytes.
#include <stdint.h>

enum
{
    PIE_Q = 0, // q0-q7
    PIE_A = 1, // a0-a15
    PIE_IMM = 2
};

struct PieField
{
    uint8_t kind;
    uint8_t nbits;
    uint8_t step; // the immediate is a multiple of it, stored divided
    int16_t min, max;
    uint8_t pos[8]; // bit k of the field goes to instruction bit pos[k]
};

struct PieOp
{
    const char *name;
    uint32_t base;
    uint8_t nops;
    bool distinctQ; // as refuses the same q register twice (ee.vzip...)
    PieField f[3];
};

