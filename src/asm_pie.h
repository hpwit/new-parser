static const PieOp *findPieOp(const char *name)
{
    for (unsigned i = 0; i < sizeof(pieOps) / sizeof(pieOps[0]); i++)
        if (strcmp(pieOps[i].name, name) == 0)
            return &pieOps[i];
    return NULL;
}

// The instruction for already checked operand values.
static uint32_t pieEncode(const PieOp *op, const int32_t *values)
{
    uint32_t code = op->base;
    for (int i = 0; i < op->nops; i++)
    {
        const PieField &f = op->f[i];
        uint32_t x = (uint32_t)(values[i] / f.step) & ((1u << f.nbits) - 1);
        for (int k = 0; k < f.nbits; k++)
            if (x >> k & 1)
                code |= 1u << f.pos[k];
    }
    return code;
}

