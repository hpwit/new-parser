TILE = {".": 0, "#": 1, "=": 2, "^": 3, "o": 4, "D": 5, "S": 6, "P": 7, "b": 8}


def rows(art, w, h):
    r = art.strip("\n").split("\n")
    assert len(r) == h and all(len(x) == w for x in r), art
    return r


def main():
    names = list(SPRITES)
    px = []
    for n in names:
        for row in rows(SPRITES[n], 8, 8):
            px += [16 if c == "." else int(c, 16) for c in row]
    tiles = []
    for k, room in enumerate(ROOMS):
        r = rows(room, 16, 15)
        flat = "".join(r)
        assert flat.count("P") == 1, k
        assert flat.count("D") == 1, k
        tiles += [TILE[c] for c in flat]
    print("// sprites: " + ", ".join("%d %s" % (i, n) for i, n in enumerate(names)))
    for i, n in enumerate(names):
        print("#define SPR_%s %d" % (n, i))
    print("#define ROOMS %d" % len(ROOMS))
    print("uint8_t sprites[%d] = {%s};" % (len(px), ", ".join(map(str, px))))
    print("uint8_t rooms[%d] = {%s};" % (len(tiles), ", ".join(map(str, tiles))))


if __name__ == "__main__":
    main()
