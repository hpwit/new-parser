TILE = {".": 0, ",": 1, "=": 2, "T": 3, "R": 4, "~": 5, "#": 6, "L": 7, "S": 8,
        "K": 9, "C": 10, "H": 11, "s": 12, "b": 13, "@": 14}


def rows(art, w, h):
    r = [x.replace(" ", ".") for x in art.strip("\n").split("\n")]
    assert len(r) == h and all(len(x) == w for x in r), (art, [len(x) for x in r])
    return r


def main():
    px = []
    names = list(ART16)
    for n in names:
        for row in rows(ART16[n], 16, 16):
            px += [4 if c == "." else int(c) for c in row]
    small = []
    names8 = list(ART8)
    for n in names8:
        for row in rows(ART8[n], 8, 8):
            small += [4 if c == "." else int(c) for c in row]
    tiles = []
    for k, room in enumerate(ROOMS):
        flat = "".join(rows(room, 10, 8))
        tiles += [TILE[c] for c in flat]
    # the screens' edges must meet
    for k in range(9):
        r = rows(ROOMS[k], 10, 8)
        if k % 3 < 2:
            o = rows(ROOMS[k + 1], 10, 8)
            assert [r[y][9] != "T" for y in range(8)] == [o[y][0] != "T" for y in range(8)], k
        if k < 6:
            o = rows(ROOMS[k + 3], 10, 8)
            assert [c != "T" for c in r[7]] == [c != "T" for c in o[0]], k
    print("// art: " + ", ".join("%d %s" % (i, n) for i, n in enumerate(names)))
    for i, n in enumerate(names):
        print("#define A_%s %d" % (n, i))
    for i, n in enumerate(names8):
        print("#define I_%s %d" % (n, i))
    print("uint8_t art[%d] = {%s};" % (len(px), ", ".join(map(str, px))))
    print("uint8_t icons[%d] = {%s};" % (len(small), ", ".join(map(str, small))))
    print("uint8_t world[%d] = {%s};" % (len(tiles), ", ".join(map(str, tiles))))


if __name__ == "__main__":
    main()
