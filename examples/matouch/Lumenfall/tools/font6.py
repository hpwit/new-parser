def glyph(ch):
    """(width, 8 rows of 0/1) for a character; an unknown one is a box."""
    rows = G.get(ch, ['###', '#.#', '#.#', '#.#', '###'])
    w = len(rows[0])
    full = [[0] * w] + [[1 if c == '#' else 0 for c in r] for r in rows]
    while len(full) < 8:
        full.append([0] * w)
    return w, full[:8]
