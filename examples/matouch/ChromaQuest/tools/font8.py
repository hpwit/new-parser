ORDER = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.:/+"

def rows(ch):
    r = [l for l in G[ch].strip("\n").split("\n")]
    assert len(r) == 8 and all(len(x) == 8 for x in r), ch
    return r

def table():
    out = []
    for ch in ORDER:
        for r in rows(ch):
            out.append(int(r.replace("#", "1").replace(".", "0"), 2))
    return out

if __name__ == "__main__":
    t = table()
    print(", ".join(str(v) for v in t))
    from art import Img
    # a preview: chrome gradient, a dark shadow
    grad = [(255, 255, 255), (220, 230, 255), (160, 180, 230), (60, 70, 120), (200, 120, 255), (255, 170, 255), (255, 230, 255), (120, 80, 160)]
    img = Img(len(ORDER) * 9 + 4, 14, (16, 14, 30))
    for k, ch in enumerate(ORDER):
        for y, r in enumerate(rows(ch)):
            for x, c in enumerate(r):
                if c == "#":
                    img.put(2 + k * 9 + x + 1, 3 + y + 1, (0, 0, 0))
        for y, r in enumerate(rows(ch)):
            for x, c in enumerate(r):
                if c == "#":
                    img.put(2 + k * 9 + x, 3 + y, grad[y])
    img.scaled(3).save(sys.argv[1] if len(sys.argv) > 1 else "font8.png")
